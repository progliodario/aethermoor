package io.github.progliodario.aethermoor.core

import java.io.File
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.boolean
import kotlinx.serialization.json.int
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import kotlinx.serialization.json.long
import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Test

/** Runs the shared conformance vectors (tests/conformance/*.json) generated by tools/gen_conformance.py. */
class ConformanceTest {
    private val repoRoot = File(System.getProperty("aether.repoRoot") ?: error("aether.repoRoot is not set"))

    private fun suite(name: String): JsonArray {
        val doc = Json.parseToJsonElement(File(repoRoot, "tests/conformance/$name.json").readText()).jsonObject
        assertEquals(name, doc.getValue("suite").jsonPrimitive.content)
        assertEquals(1, doc.getValue("spec_version").jsonPrimitive.int)
        return doc.getValue("cases").jsonArray
    }

    private fun JsonObject.long(key: String) = getValue(key).jsonPrimitive.long

    private fun JsonObject.str(key: String) = getValue(key).jsonPrimitive.content

    private fun JsonObject.hex(key: String): ULong = str(key).removePrefix("0x").toULong(16)

    private fun hexOf(element: kotlinx.serialization.json.JsonElement): ULong =
        element.jsonPrimitive.content.removePrefix("0x").toULong(16)

    private fun forEachCase(name: String, block: (label: String, input: JsonObject, expect: JsonObject) -> Unit) {
        for (case in suite(name)) {
            val c = case.jsonObject
            block(c.str("name"), c.getValue("input").jsonObject, c.getValue("expect").jsonObject)
        }
    }

    @Test
    fun rngSuite() = forEachCase("rng") { label, input, expect ->
        val values = expect["values"]?.jsonArray
        val count = (input["count"] as? JsonPrimitive)?.int ?: 0
        when (val op = input.str("op")) {
            "splitmix64" -> {
                val rng = SplitMix64(input.hex("seed"))
                for (i in 0 until count) assertEquals(hexOf(values!![i]), rng.next(), "$label[$i]")
            }
            "pcg32" -> {
                val rng = Pcg32(input.hex("init_state"), input.hex("init_seq"))
                for (i in 0 until count) assertEquals(values!![i].jsonPrimitive.long, rng.nextU32(), "$label[$i]")
            }
            "pcg32_bounded" -> {
                val rng = Pcg32(input.hex("init_state"), input.hex("init_seq"))
                val bound = input.long("bound")
                for (i in 0 until count) assertEquals(values!![i].jsonPrimitive.long, rng.nextBounded(bound), "$label[$i]")
            }
            "derive_stream" -> {
                val rng = deriveStream(input.hex("master_seed"), input.str("name"))
                for (i in 0 until count) assertEquals(values!![i].jsonPrimitive.long, rng.nextU32(), "$label[$i]")
            }
            "fnv1a64" -> assertEquals(expect.hex("value"), fnv1a64(input.str("text")), label)
            else -> error("unknown op $op")
        }
    }

    @Test
    fun hashSuite() = forEachCase("hash") { label, input, expect ->
        when (val op = input.str("op")) {
            "hash64" -> assertEquals(
                expect.hex("value"),
                hash64(input.hex("seed"), input.long("a"), input.long("b"), input.long("c")),
                label,
            )
            "lattice" -> assertEquals(expect.long("value"), lattice(input.hex("seed"), input.long("x"), input.long("y")), label)
            else -> error("unknown op $op")
        }
    }

    @Test
    fun noiseSuite() = forEachCase("noise") { label, input, expect ->
        val seed = input.hex("seed")
        when (val op = input.str("op")) {
            "noise2" -> assertEquals(expect.long("value"), noise2(seed, input.long("x"), input.long("y")), label)
            "fbm2" -> assertEquals(
                expect.long("value"),
                fbm2(seed, input.long("x"), input.long("y"), input.getValue("octaves").jsonPrimitive.int),
                label,
            )
            else -> error("unknown op $op")
        }
    }

    @Test
    fun statsSuite() = forEachCase("stats") { label, input, expect ->
        val p = input.getValue("primary").jsonObject
        val e = input.getValue("equipment").jsonObject
        val s = derivedStats(
            input.long("level"),
            Primary(p.long("str"), p.long("vit"), p.long("dex"), p.long("agi"), p.long("int"), p.long("wis"), p.long("luk")),
            Equipment(e.long("hp"), e.long("mp"), e.long("weapon_atk"), e.long("weapon_matk"), e.long("armor_def"), e.long("armor_mdef")),
        )
        assertEquals(expect.long("max_hp"), s.maxHp, "$label max_hp")
        assertEquals(expect.long("max_mp"), s.maxMp, "$label max_mp")
        assertEquals(expect.long("atk"), s.atk, "$label atk")
        assertEquals(expect.long("matk"), s.matk, "$label matk")
        assertEquals(expect.long("def"), s.def, "$label def")
        assertEquals(expect.long("mdef"), s.mdef, "$label mdef")
        assertEquals(expect.long("move_speed_x100"), s.moveSpeedX100, "$label move_speed_x100")
        assertEquals(expect.long("attack_speed_pm"), s.attackSpeedPm, "$label attack_speed_pm")
        assertEquals(expect.long("crit_chance_pm"), s.critChancePm, "$label crit_chance_pm")
        assertEquals(expect.long("crit_mult_pm"), s.critMultPm, "$label crit_mult_pm")
        assertEquals(expect.long("status_resist_pm"), s.statusResistPm, "$label status_resist_pm")
        assertEquals(expect.long("mp_regen_x100"), s.mpRegenX100, "$label mp_regen_x100")
    }

    @Test
    fun damageSuite() = forEachCase("damage") { label, input, expect ->
        val d = DamageInput(
            atk = input.long("atk"),
            powerPct = input.long("power_pct"),
            defTarget = input.long("def_target"),
            elemMultPm = input.long("elem_mult_pm"),
            penPm = input.long("pen_pm"),
            lvlAttacker = input.long("lvl_attacker"),
            lvlTarget = input.long("lvl_target"),
            variancePm = input.long("variance_pm"),
            crit = input.getValue("crit").jsonPrimitive.boolean,
            critMultPm = input.long("crit_mult_pm"),
            buffModPm = input.long("buff_mod_pm"),
        )
        assertEquals(expect.long("damage"), damage(d), label)
    }

    @Test
    fun xpSuite() {
        val pack = loadBasePack(repoRoot)
        forEachCase("xp") { label, input, expect ->
            when (val op = input.str("op")) {
                "xp_table" -> assertEquals(expect.long("value"), pack.xpToNext(input.long("level")), label)
                "xp_gain" -> assertEquals(
                    expect.long("value"),
                    xpGain(input.long("enemy_xp"), input.long("lvl_enemy"), input.long("lvl_player")),
                    label,
                )
                else -> error("unknown op $op")
            }
        }
    }

    @Test
    fun idsSuite() = forEachCase("ids") { label, input, expect ->
        assertEquals(expect.getValue("valid").jsonPrimitive.boolean, validId(input.str("text")), label)
    }

    @Test
    fun i18nFormatSuite() = forEachCase("i18n_format") { label, input, expect ->
        val args = HashMap<String, Any>()
        for ((key, value) in input.getValue("args").jsonObject) {
            val primitive = value.jsonPrimitive
            args[key] = if (primitive.isString) primitive.content else primitive.long
        }
        assertEquals(expect.str("text"), formatMessage(input.str("message"), input.str("lang"), args), label)
    }
}

internal fun loadBasePack(repoRoot: File): Pack {
    val errors = ArrayList<String>()
    val pack = loadPack(FileSystemPackSource(File(repoRoot, "data/base")), errors)
    assertEquals(emptyList<String>(), errors)
    return requireNotNull(pack)
}
