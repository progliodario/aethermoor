#!/usr/bin/env python3
"""Looks for texts that may not be translated (spec 17): writes docs/design/translations.md.

    python tools/check_translations.py          # writes the report
    python tools/check_translations.py --check  # fails when the report finds something new (not in ALLOWED)

It lists the keys whose Italian text is the same as the English one, and the Italian texts that hold common English words (and the
English texts that hold common Italian ones). Proper names and short words are the same in both languages on purpose: they go in
`ALLOWED`, by key or by text, after a look.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
I18N = ROOT / "data" / "base" / "i18n"
OUT = ROOT / "docs" / "design" / "translations.md"

ENGLISH = {"the", "and", "you", "your", "with", "this", "that", "from", "have", "will", "what", "there", "they", "were", "would"}
ITALIAN = {"il", "della", "delle", "degli", "che", "sono", "questo", "questa", "anche", "perché", "molto", "ancora", "sei"}
# texts that are the same in both languages on purpose: names of people, places and creatures, numbers, symbols
ALLOWED_TEXTS = {"Newton", "Pip", "Orb", "Mort"}
# key prefixes whose texts are names (people, places, the game) and stay the same
ALLOWED_PREFIXES = ("speaker.", "region.verdalis", "region.lumeria", "game.title", "npc.", "place.", "companion.pip", "companion.newton")


def load(lang: str) -> dict[str, str]:
    texts: dict[str, str] = {}
    for path in sorted((I18N / lang).glob("*.json")):
        texts.update({k: v for k, v in json.loads(path.read_text(encoding="utf-8")).items() if k != "$schema"})
    return texts


def words(text: str) -> set[str]:
    plain = re.sub(r"\{[^{}]*\}", " ", text)  # placeholders and plural branches are not words of the text
    return {w.lower() for w in re.findall(r"[A-Za-zÀ-ÿ']+", plain)}


def findings() -> tuple[list[str], list[str], list[str]]:
    en, it = load("en"), load("it")
    same, english_in_it, italian_in_en = [], [], []
    for key in sorted(en):
        if key not in it:
            continue
        e, i = en[key], it[key]
        allowed = key.startswith(ALLOWED_PREFIXES) or e in ALLOWED_TEXTS or (key.startswith("protagonist.") and key.endswith(".name"))
        if e == i and not allowed and len(words(e)) > 1:
            same.append(key)
        if len(words(i) & ENGLISH) >= 2:
            english_in_it.append(key)
        if len(words(e) & ITALIAN) >= 2:
            italian_in_en.append(key)
    return same, english_in_it, italian_in_en


def report() -> str:
    en, it = load("en"), load("it")
    same, english_in_it, italian_in_en = findings()
    lines = ["# Translations", "", "Generated by `tools/check_translations.py`. Do not edit by hand.", "",
             f"{len(en)} English texts, {len(it)} Italian texts.", ""]
    for title, keys in (("The same in both languages", same), ("Italian texts with English words", english_in_it),
                        ("English texts with Italian words", italian_in_en)):
        lines += [f"## {title} ({len(keys)})", ""]
        lines += [f"- `{k}`: {it.get(k, '')!r}" for k in keys] or ["None."]
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    if "--check" in sys.argv:
        found = sum(len(k) for k in findings())
        print(f"{'FAIL' if found else 'OK'}: {found} texts to look at")
        return 1 if found else 0
    OUT.write_text(report(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {sum(len(k) for k in findings())} texts to look at")
    return 0


if __name__ == "__main__":
    sys.exit(main())
