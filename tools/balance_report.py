#!/usr/bin/env python3
"""Writes docs/design/balance.md: for every creature, the player level at which a fight is comfortable, from the formulas of the rules.

    python tools/balance_report.py

The model is rough on purpose, to find outliers, not to set numbers: the player is Ren with the gear of a typical shop at each level
(`GEAR`), attacks every cooldown of the basic slash and always hits (crits at their expected rate); the enemy strikes once per windup and recovery of its
behavior and lands `LAND_PCT` percent of its strikes (the player moves). A fight is comfortable when the damage taken is at most `COMFORT_PCT` percent of the
health of the player. Use it with `docs/design/catalog.md` when tuning a creature.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from reference import rules  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "base"
OUT = ROOT / "docs" / "design" / "balance.md"

# (from level, weapon attack, armor defense, armor magic defense): what a player of that level typically wears
GEAR = [(1, 3, 2, 1), (4, 7, 4, 2), (8, 12, 7, 3), (12, 20, 9, 4), (16, 26, 12, 5), (20, 33, 14, 10), (24, 41, 15, 13)]
LAND_PCT = 60
COMFORT_PCT = 40
SLASH_TICKS = 24  # cooldown of the basic slash
MAX_LEVEL = 40


def load(folder: str) -> list[dict]:
    return [json.loads(p.read_text(encoding="utf-8")) for p in sorted((DATA / folder).rglob("*.json"))]


def player(level: int, ren: dict) -> dict[str, int]:
    base, growth = ren["base_stats"], ren["growth_pm"]
    keys = ("str", "vit", "dex", "agi", "int", "wis", "luk")
    stat = {k: base[k] + growth[k] * (level - 1) // 1000 for k in keys}
    gear = [g for g in GEAR if g[0] <= level][-1]
    primary = rules.Primary(stat["str"], stat["vit"], stat["dex"], stat["agi"], stat["int"], stat["wis"], stat["luk"])
    return rules.derived_stats(level, primary, rules.Equipment(weapon_atk=gear[1], armor_def=gear[2], armor_mdef=gear[3]))


def fight(level: int, ren: dict, enemy: dict, behavior: dict) -> tuple[float, float]:
    """(seconds to kill, share of the health of the player lost) for a player of `level` against one enemy."""
    p = player(level, ren)
    s = enemy["stats"]
    hit = rules.damage(p["atk"], 100, s["def"], 1000, 0, level, enemy["level"], 1000, False, 1500, 1000)
    crit = rules.damage(p["atk"], 100, s["def"], 1000, 0, level, enemy["level"], 1000, True, p["crit_mult_pm"], 1000)
    expected = (hit * (1000 - p["crit_chance_pm"]) + crit * p["crit_chance_pm"]) / 1000
    hits = -(-s["hp"] // max(expected, 1))
    cycle = SLASH_TICKS * 1000 // p["attack_speed_pm"]
    ticks = hits * cycle
    strike = rules.damage(s["atk"], 100, p["def"], 1000, 0, enemy["level"], level, 1000, False, 1500, 1000)
    strikes = ticks / (behavior["windup_ticks"] + behavior["recovery_ticks"])
    lost = strikes * LAND_PCT / 100 * strike / p["max_hp"]
    return ticks / 60, lost


def main() -> int:
    world = json.loads((DATA / "worlds" / "overworld.json").read_text(encoding="utf-8"))
    hp_pct = world.get("difficulty", {}).get("enemy_hp_pct", 100)
    atk_pct = world.get("difficulty", {}).get("enemy_atk_pct", 100)
    ren = json.loads((DATA / "protagonists" / "ren.json").read_text(encoding="utf-8"))
    behaviors = {b["id"]: b for b in load("behaviors")}
    names: dict[str, str] = {}
    for path in sorted((DATA / "i18n" / "en").glob("*.json")):
        names.update(json.loads(path.read_text(encoding="utf-8")))
    rows = []
    for enemy in load("enemies"):
        enemy["stats"] = {**enemy["stats"], "hp": max(1, enemy["stats"]["hp"] * hp_pct // 100), "atk": enemy["stats"]["atk"] * atk_pct // 100}  # the difficulty of the world (spec 04)
        behavior = behaviors[enemy["behavior"]]
        suggested = next((lv for lv in range(1, MAX_LEVEL + 1) if fight(lv, ren, enemy, behavior)[1] * 100 <= COMFORT_PCT), MAX_LEVEL + 1)
        at_level_seconds, at_level_lost = fight(enemy["level"], ren, enemy, behavior)
        rows.append((enemy, names.get(enemy["name"][6:], enemy["id"]), suggested, at_level_seconds, at_level_lost))
    rows.sort(key=lambda r: (r[0]["level"], r[0]["id"]))
    out = ["# Balance report", "", "Generated by `tools/balance_report.py`. Do not edit by hand. The model is rough (see the tool): it finds outliers, it does not set numbers.", "",
           f"The creatures are taken with the difficulty of the world data: health {hp_pct} percent, attack {atk_pct} percent (spec 04).", "",
           f"Gear by level: {', '.join(f'L{g[0]}: weapon {g[1]}, armor {g[2]}/{g[3]}' for g in GEAR)}. The enemy lands {LAND_PCT} percent of its strikes; comfortable means at most {COMFORT_PCT} percent of the health lost.", "",
           "| Creature | Level | Comfortable at | At its own level: seconds to kill / health lost |", "|---|---|---|---|"]
    outliers = []
    for enemy, name, suggested, seconds, lost in rows:
        out.append(f"| {name} | {enemy['level']} | {suggested if suggested <= MAX_LEVEL else '>' + str(MAX_LEVEL)} | {seconds:.1f} s / {lost * 100:.0f}% |")
        if suggested > enemy["level"] + 5 or suggested < enemy["level"] - 6:
            outliers.append((name, enemy["level"], suggested))
    out += ["", f"## Outliers ({len(outliers)})", "", "Creatures whose comfortable level differs from their level by more than 5 above or 6 below.", ""]
    out += [f"- {name}: level {level}, comfortable at {suggested if suggested <= MAX_LEVEL else '>' + str(MAX_LEVEL)}" for name, level, suggested in outliers] or ["- none"]
    OUT.write_bytes(("\n".join(out) + "\n").encode("utf-8"))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} creatures, {len(outliers)} outliers")
    return 0


if __name__ == "__main__":
    sys.exit(main())
