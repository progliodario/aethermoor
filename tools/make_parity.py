#!/usr/bin/env python3
"""The parity matrix (docs/design/parity.md): for every suite of conformance vectors (tests/conformance/*.json), the test of each
client that runs it, read from the sources of the tests.

Usage: python tools/make_parity.py [--check]
  --check   write nothing; fail when a client runs no test for a suite, or when docs/design/parity.md is not current.

Two clients, one behavior (CLAUDE.md, rule 3): a suite that only one client runs is a rule that only one client is held to. A test
"runs" a suite when its source names the suite where it loads a file of vectors: `load_suite("x")` or `run_combat_suite("x")` in
desktop/tests/*.cpp, `suite("x")`, `forEachCase("x"`, `runSuite("x")` or `tests/conformance/x.json` in the Kotlin tests of
android/core/src/test. The test is the TEST_CASE or the function (Kotlin `fun`) around that line.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VECTORS = ROOT / "tests" / "conformance"
OUT = ROOT / "docs" / "design" / "parity.md"
DESKTOP_TESTS = ROOT / "desktop" / "tests"
ANDROID_TESTS = ROOT / "android" / "core" / "src" / "test"

CPP_USE = re.compile(r'\b(?:load_suite|run_combat_suite)\("(\w+)"\)')
CPP_OWNER = re.compile(r'^(?:TEST_CASE\("([^"]+)"|(?:[\w:<>]+\s+)+(\w+)\([^;]*\)\s*\{)')
KT_USE = re.compile(r'\b(?:suite|forEachCase|runSuite)\("(\w+)"|tests/conformance/(\w+)\.json')
KT_OWNER = re.compile(r'^\s*(?:(?:private|internal|override)\s+)*fun\s+(?:[\w.<>]+\.)?(\w+)\s*\(')


def suites() -> dict[str, int]:
    """Every suite of vectors and its number of cases."""
    out = {}
    for path in sorted(VECTORS.glob("*.json")):
        doc = json.loads(path.read_text(encoding="utf-8"))
        out[path.stem] = len(doc.get("cases", []))
    return out


def uses(folder: Path, pattern: str, use: re.Pattern, owner: re.Pattern) -> dict[str, list[str]]:
    """Suite name -> the tests that load it ("file: test"), in the order of the files and the lines."""
    found: dict[str, list[str]] = {}
    for path in sorted(folder.rglob(pattern)):
        current = ""
        for line in path.read_text(encoding="utf-8").splitlines():
            head = owner.match(line)
            if head:
                current = next(g for g in head.groups() if g)
            for match in use.finditer(line):
                name = next(g for g in match.groups() if g)
                label = f"`{path.name}`: {current or '(top level)'}"
                if label not in found.setdefault(name, []):
                    found[name].append(label)
    return found


def matrix() -> tuple[str, list[str]]:
    """The text of docs/design/parity.md, and the problems (a suite a client does not run, a client loading a suite that is gone)."""
    all_suites = suites()
    desktop = uses(DESKTOP_TESTS, "*.cpp", CPP_USE, CPP_OWNER)
    android = uses(ANDROID_TESTS, "*.kt", KT_USE, KT_OWNER)
    problems = []
    rows = []
    for name, count in all_suites.items():
        d, a = desktop.get(name, []), android.get(name, [])
        if not d:
            problems.append(f"no desktop test runs the suite '{name}' (desktop/tests)")
        if not a:
            problems.append(f"no Android test runs the suite '{name}' (android/core/src/test)")
        rows.append(f"| `{name}` | {count} | {'<br>'.join(d) or '**none**'} | {'<br>'.join(a) or '**none**'} |")
    for client, found in (("desktop", desktop), ("Android", android)):
        for name in sorted(set(found) - set(all_suites)):
            problems.append(f"the {client} tests load the suite '{name}', which tests/conformance does not have")
    total = sum(all_suites.values())
    text = "\n".join([
        "# Parity matrix",
        "",
        "Generated by `tools/make_parity.py` from `tests/conformance/` and the sources of the tests of the two clients: do not edit by hand.",
        "`ci-data` runs `make_parity.py --check`, which fails when a client runs no test for a suite (CLAUDE.md, rule 3: two clients,",
        "one behavior).",
        "",
        f"{len(all_suites)} suites, {total} cases.",
        "",
        "| Suite | Cases | Desktop (`desktop/tests`) | Android (`android/core/src/test`) |",
        "|---|---|---|---|",
        *rows,
        "",
    ])
    return text, problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text, problems = matrix()
    for problem in problems:
        print("ERROR:", problem)
    current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if args.check:
        if current != text:
            print(f"OUT OF DATE: {OUT.relative_to(ROOT)} (run: python tools/make_parity.py)")
            return 1
        if not problems:
            print("OK: both clients run every suite")
    elif current != text:
        with open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print(f"wrote {OUT.relative_to(ROOT)}")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
