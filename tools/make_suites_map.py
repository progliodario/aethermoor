#!/usr/bin/env python3
"""The map of the suites (docs/design/suites.md): the categories of conformance tests that the plan names (docs/plan/02, section on the
conformance tests; docs/plan/06, the acceptance of M1 and M6) and the files and cases of tests/conformance/ that cover each of them today.

Usage: python tools/make_suites_map.py [--check]
  --check   write nothing; fail when a category covers no case any more (a case was renamed or dropped) or the document is not current.

The plan was written before the vectors: its names (`economy_price`, `crafting_quality`...) are not the names of the files. Every
category below is a list of (suite, pattern of the case names, without the prefix of the suite); a category that matches nothing is
an error, so the map cannot quietly go stale.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VECTORS = ROOT / "tests" / "conformance"
OUT = ROOT / "docs" / "design" / "suites.md"

# category of the plan: (what it checks, [(suite, regex of the case names)])
CATEGORIES = {
    "rng": ("the random streams (PCG32, SplitMix64, derived streams)", [("rng", r".")]),
    "hash": ("the hashes (FNV-1a, hash64)", [("hash", r".")]),
    "noise": ("the noise fields", [("noise", r".")]),
    "worldgen_chunk_hash": ("the world and its chunks, by digest", [("worldgen", r"."), ("worldgen_chunks", r".")]),
    "damage": ("the damage formula", [("damage", r".")]),
    "stats_derived": ("the derived stats", [("stats", r".")]),
    "xp_table": ("the table of experience", [("xp", r".")]),
    "status_ticks": ("the status effects, on the creatures and the player", [("combat", r"status|player_status")]),
    "loot_roll": ("the drops", [("combat", r"loot|bestiary|affixes_rolled")]),
    "economy_price": ("the prices of the shops: market days, renown, glut, weather, goods from afar",
                      [("combat", r"shop|market|renown_prices|renown_wares|glut|_prices|goods_from_afar|season_goods")]),
    "time_season": ("world time, the days and the seasons", [("worldtime", r"."), ("combat", r"day_cycle|season|_in_(autumn|spring|winter)")]),
    "weather": ("the weather and what it does", [("worldtime", r"."), ("combat", r"^(?!player_status).*(^|_)(rain|fog|wind|lightning|snow|night)")]),
    "quest_state_machine": ("quests: stages, objectives, rewards, repeatable and timed", [("story", r"quest"), ("combat", r"board_quest")]),
    "dialogue_eval": ("the dialogues", [("story", r"clerk|trader|decline|dialogue|smith|resident|traveller")]),
    "condition_eval": ("the conditions of the dialogues", [("story", r"trader_conditions|resident|timed"), ("combat", r"renown_dialogue|faction_dialogue")]),
    "effect_apply": ("the effects of the dialogues", [("story", r"trader|smith|barter|inn")]),
    "save_roundtrip": ("save and resume", [("save", r".")]),
    "save_migration": ("the frozen saves of every version", [("save_fixtures", r".")]),
    "i18n_format": ("the format of the texts", [("i18n_format", r".")]),
    "vector_recipe_parse": ("the art recipes and the rasterizer", [("raster", r"."), ("rig_pose", r".")]),
    "crafting_quality": ("crafting and the fine pieces", [("combat", r"craft|recipe")]),
    "week_of_play": ("a week of play (M6): farming, cooking, shops, hunting, a feast, a traveller, a timed quest", [("combat", r"week_of_play")]),
}


def cases_of(suite: str) -> list[str]:
    doc = json.loads((VECTORS / f"{suite}.json").read_text(encoding="utf-8"))
    return [c["name"].removeprefix(f"{suite}_") for c in doc["cases"]]


def build() -> tuple[str, list[str]]:
    problems = []
    rows = []
    cache: dict[str, list[str]] = {}
    for category, (what, places) in CATEGORIES.items():
        found = []
        for suite, pattern in places:
            if not (VECTORS / f"{suite}.json").exists():
                problems.append(f"{category}: the suite '{suite}' does not exist")
                continue
            names = cache.setdefault(suite, cases_of(suite))
            matched = [n for n in names if re.search(pattern, n)]
            if not matched:
                problems.append(f"{category}: no case of '{suite}' matches {pattern!r}")
            whole = len(matched) == len(names)
            found.append(f"`{suite}` (all {len(names)} cases)" if whole else f"`{suite}`: " + ", ".join(f"`{n}`" for n in matched))
        rows.append(f"| `{category}` | {what} | {'<br>'.join(found)} |")
    text = "\n".join([
        "# The suites of the plan",
        "",
        "Generated by `tools/make_suites_map.py`: do not edit by hand. The plan (`docs/plan/02`, `docs/plan/06`) names categories of",
        "conformance tests; the vectors of `tests/conformance/` were written later with other names. This is where each category is.",
        "`ci-data` runs `make_suites_map.py --check`, which fails when a category covers no case any more.",
        "",
        "| Category of the plan | What | Where (suite and cases) |",
        "|---|---|---|",
        *rows,
        "",
    ])
    return text, problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text, problems = build()
    for problem in problems:
        print("ERROR:", problem)
    current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if args.check:
        if current != text:
            print(f"OUT OF DATE: {OUT.relative_to(ROOT)} (run: python tools/make_suites_map.py)")
            return 1
        if not problems:
            print(f"OK: {len(CATEGORIES)} categories of the plan, each with its cases")
    elif current != text:
        with open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print(f"wrote {OUT.relative_to(ROOT)}")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
