#!/usr/bin/env python3
"""Writes docs/design/catalog.md: the regions, creatures, items, quests and sites of the base pack in tables (English names).

    python tools/make_catalog.py

The file is generated from `data/base`; do not edit it by hand.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from reference import worldgen  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "base"
OUT = ROOT / "docs" / "design" / "catalog.md"


def load_dir(folder: str) -> list[dict]:
    return [json.loads(p.read_text(encoding="utf-8")) for p in sorted((DATA / folder).rglob("*.json"))]


def texts() -> dict[str, str]:
    merged: dict[str, str] = {}
    for path in sorted((DATA / "i18n" / "en").glob("*.json")):
        merged.update(json.loads(path.read_text(encoding="utf-8")))
    return merged


T = texts()


def name(ref: str) -> str:
    """The English text of an `$i18n:` reference, or the last part of an id."""
    if ref.startswith("$i18n:"):
        text = T.get(ref[6:], ref[6:])
        match = re.search(r"other \{([^}]*)\}", text)  # a plural message: the plural form reads best in a table
        return match.group(1) if match else text
    return ref.rsplit("/", 1)[-1]


def short(item_id: str) -> str:
    return item_id.rsplit("/", 1)[-1]


def main() -> int:
    params = worldgen.load_params()
    enemies = {e["id"]: e for e in load_dir("enemies")}
    items = {i["id"]: i for i in load_dir("items")}
    regions = params["regions"]
    where: dict[str, list[str]] = {}
    for region in regions:
        for f in region["fauna"]:
            where.setdefault(f["enemy"], []).append(name(region["name"]))
    for stamp_id, stamp in params["stamp_defs"].items():
        for entry in stamp["legend"].values():
            if "spawner" in entry:
                where.setdefault(entry["spawner"], [])
                if stamp_id.rsplit("/", 1)[-1] not in where[entry["spawner"]]:
                    where[entry["spawner"]].append(stamp_id.rsplit("/", 1)[-1])
    out = ["# Catalog of the base pack", "", "Generated by `tools/make_catalog.py` from `data/base`. Do not edit by hand.", ""]

    out += ["## Regions", "", "| Region | Tone | Danger | Creatures | Shop |", "|---|---|---|---|---|"]
    for region in regions:
        fauna = ", ".join(f"{name(enemies[f['enemy']]['name'])} ({f['weight']})" for f in region["fauna"])
        stock = ", ".join(name(items[s]["name"]) for s in region["shop"]["stock"])
        out.append(f"| {name(region['name'])} | {region['tone']} | {region['danger']} | {fauna} | {stock} |")

    out += ["", f"## Creatures ({len(enemies)})", "", "| Creature | Level | HP | Atk | Def | MDef | Speed | Behavior | Drops | Found in |", "|---|---|---|---|---|---|---|---|---|---|"]
    for e in sorted(enemies.values(), key=lambda e: (e["level"], e["id"])):
        s = e["stats"]
        drops = ", ".join(name(items[d["item"]]["name"]) for d in e["drops"])
        out.append(f"| {name(e['name'])} | {e['level']} | {s['hp']} | {s['atk']} | {s['def']} | {s['mdef']} | {s['speed_x100'] / 100:g} | {short(e['behavior'])} | {drops} | {', '.join(where.get(e['id'], ['-']))} |")

    out += ["", f"## Items ({len(items)})", "", "| Item | Kind | Rarity | Price | Effect |", "|---|---|---|---|---|"]
    for i in sorted(items.values(), key=lambda i: (i["kind"], i.get("price", 0), i["id"])):
        if "weapon" in i:
            effect = f"attack {i['weapon']['atk']}"
        elif "armor" in i:
            effect = f"defense {i['armor']['def']}, magic defense {i['armor']['mdef']}"
        elif "use" in i:
            effect = ", ".join(f"{e['effect']} {e.get('amount', '')}".strip() for e in i["use"]["effects"])
        else:
            effect = ""
        out.append(f"| {name(i['name'])} | {i['kind']} | {i['rarity']} | {i.get('price', 0)} | {effect} |")

    quests = load_dir("quests")
    out += ["", f"## Quests ({len(quests)})", "", "| Quest | Kind | Stages | Reward |", "|---|---|---|---|"]
    for q in sorted(quests, key=lambda q: (q["kind"], q["id"])):
        reward = ", ".join(f"{r['effect']} {r.get('amount', r.get('item', ''))}" for r in q.get("rewards", [])) or "paid by the dialogue"
        out.append(f"| {name(q['name'])} | {q['kind']} | {len(q['stages'])} | {reward} |")

    out += ["", f"## Sites ({len(params['landmarks'])} landmarks)", "", "| Site | Kind | Region | Offset from the start (tiles) | Stamp |", "|---|---|---|---|---|"]
    for lm in params["landmarks"]:
        region = regions[worldgen.region_at(params, params["width"] // 2 + lm["dx"], params["height"] // 2 + lm["dy"])]
        out.append(f"| {lm['name']} | {lm['kind']} | {name(region['name'])} | ({lm['dx']}, {lm['dy']}) | {short(lm['stamp'])} |")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_bytes(("\n".join(out) + "\n").encode("utf-8"))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(enemies)} creatures, {len(items)} items, {len(quests)} quests, {len(params['landmarks'])} sites")
    return 0


if __name__ == "__main__":
    sys.exit(main())
